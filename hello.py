# 주류 우선순위 (제조 쉬운 순서)
주류_우선순위 = ["과일소주", "맥주", "하이볼", "막걸리"]
안주_목록 = ["가라아게", "타코야키", "부추전"]

주문 = {}
안주_순서 = []  # 안주 접수 순서 기록용

print("=== 이자카야 주문 입력 ===")
print("메뉴를 입력하세요. 끝내려면 '끝' 입력\n")

while True:
    메뉴 = input("주문 입력: ")
    if 메뉴 == "끝":
        break
    if 메뉴 in 주문:
        주문[메뉴] += 1
    else:
        주문[메뉴] = 1
        # 안주면 접수 순서 기록
        if 메뉴 in 안주_목록:
            안주_순서.append(메뉴)

print("\n=== 전체 주문 목록 ===")
for 메뉴, 수량 in 주문.items():
    print(f"{메뉴} x{수량}")

print("\n=== 주류 제공 순서 (우선순위 기준) ===")
for 메뉴 in 주류_우선순위:
    if 메뉴 in 주문:
        print(f"{메뉴} x{주문[메뉴]}")

print("\n=== 안주 제공 순서 (접수 순서 기준) ===")
for 메뉴 in 안주_순서:
    print(f"{메뉴} x{주문[메뉴]}")
